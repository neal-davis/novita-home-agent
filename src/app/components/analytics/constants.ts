export const flattenBtnIds: string[] = (() => {
  const result: string[] = [];

  function recurse(current: Record<string, any>) {
    for (const key in current) {
      if (typeof current[key] === "object") {
        recurse(current[key]);
      } else if (typeof current[key] === "string") {
        result.push(current[key]);
      }
    }
  }

  recurse(CLICK_BTN_IDs);
  return result;
})();

export const getGenBtnId = (rootPage: string) => {
  if (rootPage === "playground") {
    return CLICK_BTN_IDs.PLAYGROUND_GEN_BTN_ID;
  }
  if (rootPage === "product") {
    return CLICK_BTN_IDs.PRODUCT_GEN_BTN_ID;
  }
  return "";
};

